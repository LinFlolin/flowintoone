-- FLOWINTOONE: followed artisan storefronts
-- Both visitors and artisans can follow published storefronts.

begin;

create table if not exists public.business_follows (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  business_id uuid not null references public.businesses(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint business_follows_user_business_unique unique (user_id, business_id)
);

create index if not exists business_follows_user_created_idx
  on public.business_follows (user_id, created_at desc);

create index if not exists business_follows_business_idx
  on public.business_follows (business_id);

alter table public.business_follows enable row level security;

revoke all on table public.business_follows from anon;
grant select, insert, delete on table public.business_follows to authenticated;
revoke update, truncate, references, trigger on table public.business_follows from authenticated;
grant usage, select on sequence public.business_follows_id_seq to authenticated;

drop policy if exists "flowintoone_business_follows_select_own" on public.business_follows;
create policy "flowintoone_business_follows_select_own"
on public.business_follows
for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "flowintoone_business_follows_insert_own" on public.business_follows;
create policy "flowintoone_business_follows_insert_own"
on public.business_follows
for insert
to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "flowintoone_business_follows_delete_own" on public.business_follows;
create policy "flowintoone_business_follows_delete_own"
on public.business_follows
for delete
to authenticated
using ((select auth.uid()) = user_id);

commit;
