-- FLOWINTOONE: artisan products and user favourites

begin;

create table if not exists public.product_categories (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  name text not null,
  slug text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint product_categories_name_length check (char_length(btrim(name)) between 1 and 80),
  constraint product_categories_slug_length check (char_length(slug) between 1 and 90),
  constraint product_categories_business_slug_unique unique (business_id, slug)
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  category_id uuid references public.product_categories(id) on delete set null,
  code text not null,
  name text not null,
  description text,
  price_cents integer,
  currency text not null default 'EUR',
  image_url text,
  status text not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint products_code_length check (char_length(code) between 1 and 60),
  constraint products_name_length check (char_length(btrim(name)) between 1 and 140),
  constraint products_description_length check (description is null or char_length(description) <= 2000),
  constraint products_price_check check (price_cents is null or price_cents >= 0),
  constraint products_currency_check check (currency in ('EUR', 'USD', 'GBP')),
  constraint products_status_check check (status in ('draft', 'published', 'archived')),
  constraint products_business_code_unique unique (business_id, code)
);

create table if not exists public.product_favorites (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint product_favorites_user_product_unique unique (user_id, product_id)
);

-- Some environments already have a draft `products` table from an earlier
-- prototype. `create table if not exists` does not evolve that table, so add
-- the catalog columns explicitly before creating indexes and policies.
alter table public.products add column if not exists category_id uuid;
alter table public.products add column if not exists code text;
alter table public.products add column if not exists description text;
alter table public.products add column if not exists price_cents integer;
alter table public.products add column if not exists currency text not null default 'EUR';
alter table public.products add column if not exists image_url text;
alter table public.products add column if not exists status text not null default 'draft';
alter table public.products add column if not exists created_at timestamptz not null default now();
alter table public.products add column if not exists updated_at timestamptz not null default now();

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.products'::regclass
      and conname = 'products_category_id_fkey'
  ) then
    alter table public.products
      add constraint products_category_id_fkey
      foreign key (category_id) references public.product_categories(id) on delete set null;
  end if;
end
$$;

create index if not exists product_categories_business_idx on public.product_categories (business_id, sort_order, name);
create index if not exists products_business_category_idx on public.products (business_id, category_id, created_at desc);
create index if not exists products_public_idx on public.products (status, business_id, created_at desc);
create unique index if not exists products_business_code_unique_idx
  on public.products (business_id, code)
  where code is not null;
create index if not exists product_favorites_user_idx on public.product_favorites (user_id, created_at desc);
create index if not exists product_favorites_product_idx on public.product_favorites (product_id);

alter table public.product_categories enable row level security;
alter table public.products enable row level security;
alter table public.product_favorites enable row level security;

revoke all on table public.product_categories, public.products, public.product_favorites from anon;
grant select on table public.product_categories, public.products to anon;
grant select, insert, update, delete on table public.product_categories, public.products to authenticated;
grant select, insert, delete on table public.product_favorites to authenticated;
grant usage, select on sequence public.product_favorites_id_seq to authenticated;

drop policy if exists "flowintoone_product_categories_public_read" on public.product_categories;
create policy "flowintoone_product_categories_public_read"
on public.product_categories for select to anon, authenticated
using (exists (
  select 1 from public.businesses
  where businesses.id = product_categories.business_id
    and businesses.status::text = 'published'
));

drop policy if exists "flowintoone_product_categories_owner_write" on public.product_categories;
create policy "flowintoone_product_categories_owner_write"
on public.product_categories for all to authenticated
using (exists (select 1 from public.businesses where businesses.id = product_categories.business_id and businesses.owner_id = (select auth.uid())))
with check (exists (select 1 from public.businesses where businesses.id = product_categories.business_id and businesses.owner_id = (select auth.uid())));

drop policy if exists "flowintoone_products_public_read" on public.products;
create policy "flowintoone_products_public_read"
on public.products for select to anon, authenticated
using (
  products.status = 'published'
  and exists (select 1 from public.businesses where businesses.id = products.business_id and businesses.status::text = 'published')
);

drop policy if exists "flowintoone_products_owner_read" on public.products;
create policy "flowintoone_products_owner_read"
on public.products for select to authenticated
using (exists (select 1 from public.businesses where businesses.id = products.business_id and businesses.owner_id = (select auth.uid())));

drop policy if exists "flowintoone_products_owner_insert" on public.products;
create policy "flowintoone_products_owner_insert"
on public.products for insert to authenticated
with check (exists (select 1 from public.businesses where businesses.id = products.business_id and businesses.owner_id = (select auth.uid())));

drop policy if exists "flowintoone_products_owner_update" on public.products;
create policy "flowintoone_products_owner_update"
on public.products for update to authenticated
using (exists (select 1 from public.businesses where businesses.id = products.business_id and businesses.owner_id = (select auth.uid())))
with check (exists (select 1 from public.businesses where businesses.id = products.business_id and businesses.owner_id = (select auth.uid())));

drop policy if exists "flowintoone_products_owner_delete" on public.products;
create policy "flowintoone_products_owner_delete"
on public.products for delete to authenticated
using (exists (select 1 from public.businesses where businesses.id = products.business_id and businesses.owner_id = (select auth.uid())));

drop policy if exists "flowintoone_product_favorites_select_own" on public.product_favorites;
create policy "flowintoone_product_favorites_select_own"
on public.product_favorites for select to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "flowintoone_product_favorites_insert_own" on public.product_favorites;
create policy "flowintoone_product_favorites_insert_own"
on public.product_favorites for insert to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "flowintoone_product_favorites_delete_own" on public.product_favorites;
create policy "flowintoone_product_favorites_delete_own"
on public.product_favorites for delete to authenticated
using ((select auth.uid()) = user_id);

create or replace function public.flowintoone_products_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists flowintoone_products_set_updated_at on public.products;
create trigger flowintoone_products_set_updated_at
before update on public.products
for each row execute function public.flowintoone_products_set_updated_at();

commit;
